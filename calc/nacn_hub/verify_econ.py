# -*- coding: utf-8 -*-
"""ЭКОНОМИКА РЫЧАГА НА ДОСТИЖИМЫХ ОБЪЁМАХ (пул пересчитан в verify_pool.py)"""
Q0, CAPEX0 = 2500.0, 10.22e6
# статьи денежной себестоимости при 2500 т/год: (низ, верх, показатель степени)
# e=1.0 -> удельная не меняется; e<1 -> удельная падает как (Q/Q0)^(e-1); None -> как капитал
ITEMS=[("мочевина",506,584,1.0),("едкий натр",512,537,1.0),("щёлочь на CO2",56,112,1.0),
 ("природный газ",104,302,1.0),("электроэнергия",57,122,1.0),("вода",9,29,1.0),
 ("катализатор Pt/Rh",20,40,1.0),("обезвреж. стоков",22,38,1.0),
 ("персонал",166,300,0.30),("ТОиР",143,204,None),("страхование",35,55,None),("ICMI/лаб",30,48,0.25)]
CRF=lambda r,n: r/(1-(1+r)**-n); K=CRF(0.12,15)
LOAD_LO,LOAD_HI = 1.46e6, 3.10e6      # узел налива автоцистерн (снят по безопасности — возвращается)
def cx(Q,n): return CAPEX0*(Q/Q0)**n
def cash(Q,n,hi):
    return sum((h if hi else l)*(Q/Q0)**((n if e is None else e)-1.0) for _,l,h,e in ITEMS)
def trip(km,hi):                       # $/т NaCN, автоцистерна 20 м3 = 6.78 т NaCN
    d=2*km; f=d*0.35*(1.25 if hi else 1.05); c=35 if hi else 20
    e=(90 if hi else 50)+d*(0.30 if hi else 0.15); t=(110 if hi else 60)+d*(0.60 if hi else 0.35)
    return (f+c+e+t)*(1.30 if hi else 1.18)/6.78

print("="*100); print("A. ГЛАВНЫЙ ФАКТ: сколько СВОБОДНОГО объёма даёт «плечо 0 км»"); print("="*100)
print(f"База проекта              : {Q0:6.0f} т/год")
print(f"Весь спрос Тарквы (LOM,[П]): {3010:6.0f} т/год")
print(f"=> запас на нулевом плече : {3010-Q0:6.0f} т/год = +{(3010/Q0-1)*100:.0f}% к базе, и это ПОТОЛОК")
print(f"   база уже забирает {Q0/3010*100:.0f}% всего спроса якоря — «двигаться по кривой» некуда")

# конфигурации: имя, Q, [(кт/год, км)] внеплощадочных, нужен ли узел налива, комментарий
CFG=[("A база (как в модели)",              2500, [],                    False,"—"),
     ("B Тарква 100%, труба, 0 цистерн",    3010, [],                    False,"чистая версия рычага"),
     ("C +Идуаприем 17 км",                 4400, [(1.39,17)],           True, "клиент Orica, узел налива"),
     ("D +Даманг 30 км",                    5900, [(1.39,17),(1.50,30)], True, "новый владелец E&P, ICMI с нуля"),
     ("E кольцо 8 кт (заявка автора)",      8000, [(1.39,17),(1.50,30),(1.10,35),(2.00,88)], True,
                                                                                "требует вытеснить Orica у 4-5 рудников")]
print("\n"+"="*100); print(f"B. КРИВАЯ ПОЛНОЙ СЕБЕСТОИМОСТИ (CRF 12 проц. / 15 лет = {K:.5f})"); print("="*100)
h=f"{'конфигурация':34s}{'Q,т/г':>7s}{'капитал, млн$':>16s}{'денеж.$/т':>13s}{'кап.заряд':>11s}{'достав.':>9s}{'ПОЛНАЯ $/т':>16s}"
print(h); print("-"*len(h))
R={}
for nm,Q,offs,need,cm in CFG:
    cl,ch = cx(Q,0.62), cx(Q,0.72)
    if need: cl+=LOAD_LO; ch+=LOAD_HI
    dl=sum(kt*1000*trip(km,False) for kt,km in offs)/Q
    dh=sum(kt*1000*trip(km,True ) for kt,km in offs)/Q
    ml,mh=cash(Q,0.62,False),cash(Q,0.72,True)
    kl,kh=cl*K/Q, ch*K/Q
    fl,fh=ml+kl+dl, mh+kh+dh
    R[nm]=dict(Q=Q,cl=cl,ch=ch,ml=ml,mh=mh,dl=dl,dh=dh,fl=fl,fh=fh)
    print(f"{nm:34s}{Q:7.0f}{cl/1e6:8.2f}-{ch/1e6:6.2f}{ml:7.0f}-{mh:5.0f}{kl:6.0f}-{kh:4.0f}{dl:5.0f}-{dh:3.0f}{fl:9.0f}-{fh:6.0f}")

b=R["A база (как в модели)"]
print("\n"+"="*100); print("C. ЭФФЕКТ РЫЧАГА ОТНОСИТЕЛЬНО БАЗЫ 2500 т/год"); print("="*100)
for nm,Q,offs,need,cm in CFG[1:]:
    r=R[nm]
    print(f"  {nm:34s} эффект {r['fl']-b['fl']:+7.0f} ... {r['fh']-b['fh']:+7.0f} $/т | "
          f"капитал {(r['cl']-CAPEX0)/1e6:+6.2f}...{(r['ch']-CAPEX0)/1e6:+6.2f} млн | {cm}")
print(f"\n  ЗАЯВЛЕНО АВТОРОМ: -400...-600 $/т при капитале +7.7...+15.2 млн")

print("\n"+"="*100); print("D. ЦЕНОВАЯ СТОРОНА: что происходит с реализуемой ценой"); print("="*100)
PAR=2207.0; CEIL=2596.0; S=CEIL-PAR
print(f"  паритет с импортом $ {PAR:.0f}/т; потолок brownfield-желания рудника $ {CEIL:.0f}/т; излишек $ {S:.0f}/т")
print("  ВОЗРАЖЕНИЕ АВТОРУ: он считает концентрацию ЦЕНОЙ роста. Знак обратный —")
print(f"    база 2500 т: единственный покупатель = Gold Fields, {2500/2500*100:.0f}% выручки (концентрация УЖЕ полная)")
for nm in ("C +Идуаприем 17 км","D +Даманг 30 км","E кольцо 8 кт (заявка автора)"):
    Q=R[nm]['Q']; print(f"    {nm:34s}: Gold Fields = {3010/Q*100:4.0f}% выручки -> зависимость ПАДАЕТ")
print("  Реальная ценовая плата другая: доля национального рынка.")
for nm in ("A база (как в модели)","B Тарква 100%, труба, 0 цистерн","D +Даманг 30 км","E кольцо 8 кт (заявка автора)"):
    Q=R[nm]['Q']; print(f"    {nm:34s}: {Q/19000*100:4.0f}% внутреннего потребления Ганы (18-20 кт)")
PEN_LO,PEN_HI = 40.0, 110.0   # [Д] сжатие переговорного излишка при 4-6 покупателях и доле рынка >30%
print(f"  принимаю сжатие цены {PEN_LO:.0f}-{PEN_HI:.0f} $/т [Д] для конфигураций D и E (не для B: там 1 покупатель как и в базе)")

print("\n"+"="*100); print("E. НЕТТО-ЭФФЕКТ И ОКУПАЕМОСТЬ"); print("="*100)
for nm,Q,offs,need,cm in CFG[1:]:
    r=R[nm]; pen = 0.0 if Q<=3010 else None
    lo_pen, hi_pen = (0,0) if Q<=3010 else (PEN_LO,PEN_HI)
    print(f"  {nm:34s} НЕТТО {r['fl']-b['fl']+lo_pen:+7.0f} ... {r['fh']-b['fh']+hi_pen:+7.0f} $/т")
print()
for price,lab in ((2207,"паритет с импортом"),(2757,"greenfield-середина")):
    print(f"  --- цена {price} $/т ({lab}) ---")
    for nm,Q,offs,need,cm in CFG:
        r=R[nm]
        for cap,cc,dd,tag in ((r['cl'],r['ml'],r['dl'],"низ"),(r['ch'],r['mh'],r['dh'],"верх")):
            p = price - (0 if Q<=3010 else (PEN_LO if tag=="низ" else PEN_HI))
            eb=(p-cc-dd)*Q; pb=cap/eb if eb>0 else 1e9
            print(f"     {nm:34s} {tag:4s} EBITDA {eb/1e6:6.2f} млн  окуп. {('%.1f г'%pb) if pb<60 else 'НЕ ОКУПАЕТСЯ'}")

print("\n"+"="*100); print("F. ЧУВСТВИТЕЛЬНОСТЬ: а если Тарква даст только базовые 2500 т?"); print("="*100)
print("   (построили под 5900 т, законтрактовали меньше — Orica удержала Идуаприем и Даманг)")
Qn=5900
for Qa in (5900,4400,3010,2500):
    out=[]
    for hi,n in ((False,0.62),(True,0.72)):
        cap=cx(Qn,n)+(LOAD_HI if hi else LOAD_LO)
        # переменные по факту, условно-постоянные по номиналу
        var=sum((h if hi else l)*Qn*(Qn/Q0)**(e-1.0) for _,l,h,e in ITEMS if e==1.0)/Qn*Qa
        fix=sum((h if hi else l)*Qn*(Qn/Q0)**((n if e is None else e)-1.0) for _,l,h,e in ITEMS if e!=1.0)
        out.append((var+fix+cap*K)/Qa)
    print(f"   номинал {Qn} т, факт {Qa:5d} ({Qa/Qn*100:3.0f}%): полная {out[0]:5.0f} - {out[1]:5.0f} $/т"
          f"  (база 2500 т: {b['fl']:.0f} - {b['fh']:.0f})")
