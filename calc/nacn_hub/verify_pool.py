print(f"  -> интенсивность {i_tarkwa:.4f} кг/т руды  [П]")
print(f"Метод автора 0.30-0.50 кг/т завышает интенсивность Тарквы "
      f"в {0.30/i_tarkwa:.2f}-{0.50/i_tarkwa:.2f} раза")
# лабораторная testwork Тарквы (та же 43-101, Table 13.3) - подтверждает низкий расход
lab=[0.35,0.15,0.26,0.14,0.18,0.16,0.28,0.21]
print(f"Bottle-roll testwork Тарквы (Table 13.3): {min(lab)}-{max(lab)}, среднее {sum(lab)/len(lab):.3f} кг/т [П]")
print(f"  отношение план/лаборатория = {i_tarkwa/(sum(lab)/len(lab)):.2f} -> план УЖЕ включает заводские потери")

print(f"\nАвтор: Тарква 13.6 Мт -> '5-8 кт NaCN'.  Факт по плану LOM: {sum(cn)/7:,.0f} т.")
