Q0,CAPEX0=2500.0,10.22e6
ITEMS=[("var",1131,1462,1.0),("персонал",166,300,0.30),("ТОиР",143,204,None),
       ("страх",35,55,None),("ICMI",30,48,0.25)]
# var = 506+512+56+104+57+9+20+22 = 1286? пересчёт ниже
VAR_LO=506+512+56+104+57+9+20+22; VAR_HI=584+537+112+302+122+29+40+38
ITEMS[0]=("var",VAR_LO,VAR_HI,1.0)
CRF=lambda r,n: r/(1-(1+r)**-n)
def cx(Q,n,pen=0.0): return CAPEX0*(Q/Q0)**n*(1+(pen if Q>6000 else 0))
def fixedcost(Qn,n,idx):
    """годовые условно-постоянные + переменные при НОМИНАЛЕ Qn"""
    out={}
    for nm,l,h,e in ITEMS:
        e=n if e is None else e
        out[nm]=(l if idx==0 else h)*Qn*(Qn/Q0)**(e-1)
    return out

print("=== 1. ЧУВСТВИТЕЛЬНОСТЬ К СТАВКЕ ВОЗВРАТА КАПИТАЛА ===")
print(f"{'ставка/срок':>14s} {'CRF':>8s} {'кап.заряд 2500':>15s} {'8000':>8s} {'эффект $/т':>12s}")
for r,n_,lab in ((0.10,20,"10%/20 лет"),(0.12,15,"12%/15 лет"),(0.15,10,"15%/10 лет")):
    k=CRF(r,n_)
    a=CAPEX0*k/2500
    b_lo=(cx(8000,0.62)+1.46e6)*k/8000; b_hi=(cx(8000,0.72,0.18)+3.10e6)*k/8000
    print(f"{lab:>14s} {k:8.4f} {a:13.0f} $/т {b_lo:5.0f}-{b_hi:4.0f} {b_lo-a:6.0f}...{b_hi-a:5.0f}")

print("\n=== 2. РИСК ЗАГРУЗКИ: построили под 8 кт, законтрактовали меньше ===")
print("(Тарква по методу 0.3-0.5 кг/т = 4.08-6.80 кт — 8 кт БЕЗ второго рудника недостижимы)")
k=CRF(0.12,15)
for Qn in (8000,):
    for Qa in (8000,7000,6000,5000,4100):
        for idx,n,pen,lab in ((0,0.62,0.0,"низ"),(1,0.72,0.18,"верх")):
            f=fixedcost(Qn,n,idx); cap=cx(Qn,n,pen)+1.46e6
            var=f["var"]/Qn*Qa                       # переменные по факту
            fix=sum(v for kk,v in f.items() if kk!="var")   # постоянные по номиналу
            full=(var+fix+cap*k)/Qa
            if idx==0: line=f"  номинал {Qn}, факт {Qa:5d} ({Qa/Qn*100:3.0f}%): полная {full:5.0f}"
            else: print(line+f" - {full:5.0f} $/т")
print("  для сравнения база 2500 т: 2260 - 2971 $/т")

print("\n=== 3. РАЗЛОЖЕНИЕ ЭФФЕКТА 2500 -> 8000 т/год (низ / верх) ===")
for idx,n,pen,lab in ((0,0.62,0.0,"НИЗ"),(1,0.72,0.18,"ВЕРХ")):
    print(f"  --- {lab} ---")
    tot=0
    for nm,l,h,e in ITEMS:
        e2=n if e is None else e
        v=(l if idx==0 else h); d=v*((8000/Q0)**(e2-1)-1); tot+=d
        print(f"    {nm:10s} {v:6.0f} -> {v*(8000/Q0)**(e2-1):6.0f}  {d:+7.0f} $/т")
    cap0=CAPEX0*k/2500; cap1=(cx(8000,n,pen)+1.46e6 if idx==0 else cx(8000,n,pen)+3.10e6)*k/8000
    print(f"    {'кап.заряд':10s} {cap0:6.0f} -> {cap1:6.0f}  {cap1-cap0:+7.0f} $/т")
    dl = (2.0*1000*((2*10*0.35*1.05+20+(50+2*10*0.15)+(60+2*10*0.35))*1.18/6.78))/8000 if idx==0 else \
         (2.0*1000*((2*10*0.35*1.25+35+(90+2*10*0.30)+(110+2*10*0.60))*1.30/6.78))/8000
    print(f"    {'доставка':10s} {0:6.0f} -> {dl:6.0f}  {dl:+7.0f} $/т")
    print(f"    ИТОГО ВАЛОВОЙ ЭФФЕКТ {tot+cap1-cap0+dl:+.0f} $/т")
    print(f"    цена концентрации    {+97 if idx==0 else +117:+.0f} $/т")
    print(f"    НЕТТО                {tot+cap1-cap0+dl+(97 if idx==0 else 117):+.0f} $/т")
