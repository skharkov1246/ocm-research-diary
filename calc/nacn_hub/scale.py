import math
Q0=2500.0; CAPEX0=10.22e6
# --- денежная себестоимость при 2500 т/год, статья за статьёй (из audit_cost_out.txt) ---
# (низ, верх, показатель степени n: удельная стоимость масштабируется как (Q/Q0)^(n-1))
ITEMS=[
 ("мочевина",        506,584,1.00),("едкий натр",      512,537,1.00),
 ("NaOH на CO2",      56,112,1.00),("природный газ",   104,302,1.00),
 ("электроэнергия",   57,122,1.00),("вода",              9, 29,1.00),
 ("катализатор Pt/Rh",20, 40,1.00),("обезвреж. стоков", 22, 38,1.00),
 ("персонал",        166,300,0.30),   # штат растёт как Q^0.25-0.35
 ("ТОиР",            143,204,None),   # % от капитала -> степень капитала
 ("страхование",      35, 55,None),   # то же
 ("ICMI/лаборатория", 30, 48,0.25),
]
CRF=lambda r,n: r/(1-(1+r)**-n)
CRF_BASE=CRF(0.12,15)

def capex(Q, n, modloss_kt=6000.0, modpen=0.0):
    c=CAPEX0*(Q/Q0)**n
    if Q>modloss_kt: c*= (1+modpen)          # потеря ISO-модульности выше ~6 кт
    return c

def cash(Q,n):
    lo=hi=0.0
    for _,l,h,e in ITEMS:
        ee = n if e is None else e
        f=(Q/Q0)**(ee-1.0)
        lo+=l*f; hi+=h*f
    return lo,hi

print("=== A. КРИВАЯ ПОЛНОЙ СЕБЕСТОИМОСТИ (без доставки, без труб) ===")
print("капитал: 10.22 млн x (Q/2500)^n ; n=0.62 (низ) / 0.72 + 18% потеря модульности (верх)")
print(f"аннуитет CRF(12%,15 лет)={CRF_BASE:.5f}\n")
print(f"{'Q,т/год':>8s} {'капитал,млн$ низ-верх':>24s} {'денежн. $/т':>16s} {'кап.заряд $/т':>17s} {'ПОЛНАЯ $/т':>18s}")
res={}
for Q in (2500,6000,8000,10000,12000):
    cl=capex(Q,0.62); ch=capex(Q,0.72,modpen=0.18)
    ml,mh=cash(Q,0.62),cash(Q,0.72)
    kl=cl*CRF_BASE/Q; kh=ch*CRF_BASE/Q
    fl=ml[0]+kl; fh=mh[1]+kh
    res[Q]=dict(cl=cl,ch=ch,cash_lo=ml[0],cash_hi=mh[1],full_lo=fl,full_hi=fh,k_lo=kl,k_hi=kh)
    print(f"{Q:8d} {cl/1e6:11.2f} -{ch/1e6:9.2f} {ml[0]:8.0f} -{mh[1]:6.0f} {kl:9.0f} -{kh:6.0f} {fl:10.0f} -{fh:6.0f}")

print("\n=== B. ЭФФЕКТ МАСШТАБА ОТ 2500 т/год (голая кривая) ===")
b=res[2500]
for Q in (6000,8000,10000,12000):
    r=res[Q]
    print(f"  2500 -> {Q:6d} т/год: низ {r['full_lo']-b['full_lo']:+7.0f} $/т, верх {r['full_hi']-b['full_hi']:+7.0f} $/т")

print("\n=== C. ПРОВЕРКА ЗАЯВЛЕННОГО КАПИТАЛА АВТОРА ===")
for Q,claim in ((8000,17.9e6),(12000,25.5e6)):
    n_impl=math.log(claim/CAPEX0)/math.log(Q/Q0)
    print(f"  {Q} т: автор {claim/1e6:.1f} млн -> подразумевает степень n={n_impl:.3f}"
          f"  | мой диапазон {capex(Q,0.62)/1e6:.1f}-{capex(Q,0.72,modpen=0.18)/1e6:.1f} млн")
print("  типовая степень для хим. установок 0.6-0.7; n<0.60 не обоснована,")
print("  а выше ~6 кт колонна абсорбера и реактор перестают быть ISO-габаритом.")

print("\n=== D. ГАЗ И ЭЛЕКТРИЧЕСТВО ПРИ МАСШТАБЕ ===")
HHV=1030.0; DAYS=350
for Q in (2500,8000,10000,12000):
    mmbtu=27.5*Q; mmscfd=mmbtu*1e6/HHV/DAYS/1e6
    mw=640*Q/1000/(DAYS*24)
    print(f"  {Q:6d} т: газ {mmscfd:5.3f} MMSCFD ({mmscfd/135*100:5.2f}% от Genser 135) | ср. эл. нагрузка {mw:5.2f} МВт")
