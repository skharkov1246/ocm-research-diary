# 1. ПУЛ В РАДИУСЕ ТРУБЫ — пересчёт методом автора и проверка его арифметики
I_LO, I_HI = 0.30, 0.50   # кг NaCN / т руды  [Д]

mines = [
 # имя, помол Мт/год, км от Тарквы (дорога), владелец, статус
 ("Tarkwa (GFI)",        13.6,   0, "Gold Fields",  "работает"),
 ("Iduapriem (AGA)",      5.7,  10, "AngloGold",    "работает"),   # ПРОПУЩЕН у автора
 ("Damang (GFI)",         4.5,  30, "Gold Fields",  "работает, ресурс до ~2028"),
 ("Wassa (Chifeng)",      1.7,  35, "Chifeng",      "работает"),   # ПРОПУЩЕН у автора
 ("Prestea/Bogoso",       1.2,  30, "FGR",          "C&M / нестабилен"),
 ("Edikan (Perseus)",     7.0,  85, "Perseus",      "работает"),
 ("Chirano (Asante)",     2.5,  85, "Asante",       "работает"),
 ("Bibiani (Asante)",     2.0,  95, "Asante",       "работает"),
]
print(f"{'рудник':22s} {'Мт/год':>7s} {'км':>4s} {'кт NaCN low':>12s} {'high':>7s}")
tl=th=0
for n,mt,km,own,st in mines:
    lo, hi = mt*I_LO, mt*I_HI
    tl+=lo; th+=hi
    print(f"{n:22s} {mt:7.1f} {km:4d} {lo:12.2f} {hi:7.2f}   {own}, {st}")
print(f"{'ИТОГО 100 км':22s} {'':7s} {'':4s} {tl:12.2f} {th:7.2f}")

def band(pred,label):
    l=sum(m[1]*I_LO for m in mines if pred(m)); h=sum(m[1]*I_HI for m in mines if pred(m))
    print(f"{label:42s} {l:6.2f} - {h:6.2f} кт/год")
band(lambda m: m[2]<=0,  "  только Тарква (плечо 0 км)")
band(lambda m: m[2]<=10, "  Тарква+Идуаприем (<=10 км, 2 владельца)")
band(lambda m: m[2]<=30 and m[0].startswith(('Tarkwa','Damang')), "  Тарква+Даманг (версия автора, 1 владелец)")
band(lambda m: m[2]<=35, "  ядро <=35 км (5 рудников)")
band(lambda m: m[2]<=95, "  всё кольцо 100 км")

print("\n--- проверка арифметики автора ---")
print(f"автор: Тарква 13.6 Мт -> '5-8 кт'. Метод 0.3-0.5 кг/т даёт {13.6*I_LO:.2f}-{13.6*I_HI:.2f} кт.")
print(f"  верх завышен на {(8-6.8)/6.8*100:.0f}%, низ завышен на {(5-4.08)/4.08*100:.0f}%")
au_lo = 4.08+1.35+2.1+0.75+0.6+0.3; au_hi=6.8+2.25+3.5+1.25+1.0+0.8
print(f"сумма авторского набора по ЕГО ЖЕ методу: {au_lo:.2f}-{au_hi:.2f} кт (заявлено 10.2-16.9)")
print(f"Тарква+Даманг по методу: {13.6*I_LO+4.5*I_LO:.2f}-{13.6*I_HI+4.5*I_HI:.2f} кт (заявлено 6.4-10.3)")

print("\n--- перекрёстная проверка интенсивности по золоту ---")
# Тарква ~500 kozAu/год; стоимость цианида на унцию
for kt in (4.08, 5.44, 6.80):
    print(f"  {kt:.2f} кт NaCN x $2200/т / 500 koz = ${kt*1000*2200/500000:5.1f}/oz  (норма 15-35 $/oz)")
print("\n--- доля национального потребления (внутр. 18-20 кт/год) ---")
for q in (6,8,10,12):
    print(f"  завод {q} кт = {q/19*100:4.0f}% всего внутреннего рынка Ганы")
