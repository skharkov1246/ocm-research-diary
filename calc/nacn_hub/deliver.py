# === ДОСТАВКА: труба против автоцистерны. Ключ — товар это 30% РАСТВОР ===
C=0.30; RHO=1.13          # т NaCN / т раствора ; плотность раствора т/м3
TON_SOL=1/C               # 3.333 т раствора на 1 т NaCN
print(f"на 1 т NaCN перевозится {TON_SOL:.2f} т 30%-раствора -> любой $/т-км умножается на {TON_SOL:.2f}")

# --- А. автоцистерна снизу вверх ---
V=20.0                    # м3 автоцистерны
load_sol=V*RHO; load_nacn=load_sol*C
print(f"\nАВТОЦИСТЕРНА {V:.0f} м3: {load_sol:.1f} т раствора = {load_nacn:.2f} т NaCN за рейс")
def trip(km_one, lo=True):
    km=2*km_one
    fuel = km*0.35*(1.05 if lo else 1.25)          # 35 л/100км, дизель $1.05-1.25/л [Д]
    crew = 20 if lo else 35
    escort = (50 if lo else 90) + km*(0.15 if lo else 0.30)   # сопровождение по ICMI
    truck = (60 if lo else 110) + km*(0.35 if lo else 0.60)   # владение+ТОиР+страх. опасного груза
    ovh   = 0.18 if lo else 0.30
    return (fuel+crew+escort+truck)*(1+ovh)
print(f"{'плечо,км':>9s} {'$/рейс низ-верх':>18s} {'$/т NaCN низ-верх':>20s} {'$/т-км по раствору':>20s}")
truck_cost={}
for km in (10,30,35,70,85,95):
    lo,hi=trip(km,True),trip(km,False)
    a,b=lo/load_nacn,hi/load_nacn
    truck_cost[km]=(a,b)
    print(f"{km:9d} {lo:8.0f} -{hi:7.0f} {a:11.0f} -{b:7.0f} {a/TON_SOL/km:9.3f}-{b/TON_SOL/km:6.3f}")

print("\nперекрёстная проверка по якорю из меморандума:")
print("  Тема->ворота рудника $125-217/т для ТВЁРДОГО цианида, ~320 км.")
print("  портовые сборы/перевалка оценим $45-75/т -> сухопутное плечо $80-142/т на 320 км")
for lo,hi,pl in ((80,142,320),):
    print(f"  => {lo/pl:.3f}-{hi/pl:.3f} $/т-км по ТВЁРДОМУ грузу")
    for km in (10,30,85):
        print(f"     на {km:2d} км для 30%-раствора: {lo/pl*km*TON_SOL:5.0f} - {hi/pl*km*TON_SOL:5.0f} $/т NaCN")

# --- Б. трубопровод снизу вверх, $/км ---
print("\nТРУБОПРОВОД (DN80 HDPE PE100 в защитном кожухе, закопан, с течеобнаружением)")
comp={"труба+кожух PE100, $/м":(25,36),"траншея/засыпка, $/м":(25,60)}
fixed={"насосная+КИП+SCADA+течеобнаружение":(0.40e6,0.80e6),
       "переходы (дороги/водотоки), 0.6/км":(0,0),
       "отвод земли, EIA/L.I.2504, компенсации":(0.20e6,0.50e6),
       "приёмный узел на руднике (врезка в CIL)":(0.12e6,0.28e6)}
def pipe(km):
    lo=hi=0
    for k,(a,b) in comp.items(): lo+=a*km*1000; hi+=b*km*1000
    lo+=0.40e6+0.20e6+0.12e6; hi+=0.80e6+0.50e6+0.28e6
    lo+=0.6*km*30e3; hi+=0.6*km*80e3       # переходы
    return lo*1.30, hi*1.30                # инжиниринг+резерв 30%
for km in (10,30,85):
    a,b=pipe(km); print(f"  {km:2d} км: ${a/1e6:5.2f} - {b/1e6:5.2f} млн  (= ${a/km/1e3:4.0f}-{b/km/1e3:4.0f} тыс/км)")

# --- В. что дешевле на реальных объёмах ---
print("\nСРАВНЕНИЕ на горизонте 15 лет, ставка 12% (аннуитет-фактор 6.811):")
AF=6.8109
for name,km,kt in (("Идуаприем",10,2.3),("Даманг",30,1.8),("Эдикан",85,2.8)):
    tl,th=truck_cost[km]; pl,ph=pipe(km)
    print(f"  {name:10s} {km:2d} км, {kt:.1f} кт/год:")
    print(f"     автоцистерны: ${tl*kt*1000/1e6:.2f}-{th*kt*1000/1e6:.2f} млн/год -> PV ${tl*kt*1000*AF/1e6:.1f}-{th*kt*1000*AF/1e6:.1f} млн")
    print(f"     труба       : CAPEX ${pl/1e6:.2f}-{ph/1e6:.2f} млн + прокачка ~$3-6/т")
    print(f"     => дешевле: {'ТРУБА' if pl < tl*kt*1000*AF else 'ЦИСТЕРНЫ'} (по низу), "
          f"{'ТРУБА' if ph < th*kt*1000*AF else 'ЦИСТЕРНЫ'} (по верху)")
