# --- механика: ASME VIII-1 UG-27, обечайка, SS316L
def S_allow(TC):   # [H] ASME II-D, SA-240 316L, МПа (интерполяция по табличным точкам)
    pts=[(38,115.0),(100,102.0),(150,95.0),(200,90.0),(250,86.0)]
    if TC<=pts[0][0]: return pts[0][1]
    for i in range(len(pts)-1):
        if pts[i][0]<=TC<=pts[i+1][0]:
            f=(TC-pts[i][0])/(pts[i+1][0]-pts[i][0]); return pts[i][1]+f*(pts[i+1][1]-pts[i][1])
    return pts[-1][1]
CA=1.5   # мм припуск на коррозию
def wall(P_op,TC,D_mm=600.0,E=1.0):
    Pd=P_op*1.25+1.0                      # расчётное давление, бар(абс)
    S=S_allow(TC+30.)                     # расчётная T = рабочая +30 K
    t=(Pd/10.)*(D_mm/2.)/(S*E-0.6*(Pd/10.))
    return Pd, S, t, math.ceil(t+CA)      # округление вверх до целого мм листа
def shell_kg(D_mm,L_m,t_mm,rho=8000.):
    Dm=D_mm/1000.+t_mm/1000.
    m_sh=math.pi*Dm*L_m*(t_mm/1000.)*rho
    m_hd=2*1.24*(D_mm/1000.)**2*(t_mm/1000.)*rho     # 2 эллиптических днища 2:1
    return m_sh+m_hd
# --- стоимость: Towler & Sinnott, табл.7.2, вертикальный сосуд, USGC 2010:
#     C = 17400 + 79*S^0.85, S = масса кг (160..250 000); f_mat(316L)=1.3
CEPCI=800./532.9      # [Т] CEPCI 2025 / 2010
FCHINA=0.60           # [Д] Китай FOB / USGC, 0.55-0.70
def vessel_usd(mass_kg, fab=1.40):
    S=mass_kg*fab     # днища/штуцера/фланцы/юбка/внутренние = +40%
    return (17400.+79.*S**0.85)*1.30*CEPCI*FCHINA, S

