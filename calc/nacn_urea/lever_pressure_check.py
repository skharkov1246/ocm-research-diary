def burner(nov):
    F=dict(BASE_FEED); F["CO2"]=nCO2; F["H2O"]=nov
    P2=dict(prod); P2["CO2"]=P2.get("CO2",0.)+nCO2; P2["H2O"]=P2["H2O"]+nov
