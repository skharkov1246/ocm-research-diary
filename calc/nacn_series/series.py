def unit(N, cont_rate, same_site=False, new_juris=False, realize=1.0):
    mat = EQ_mat*(1-(QTY_DISC if N>1 else 0))
    lab = EQ_lab*N**b(PF_SHOP)
    logi= LOGI
    smr = SMR*N**b(PF_FIELD)
    eng = ENG_rec*N**b(PF_ENG) + (nonrec if N==1 else nonrec*(1-realize))
    if N>1 and new_juris: eng += nonrec*0.40*realize   # ре-сертификация в новой юрисдикции
    if same_site and N>1:            # общая площадка: мобилизация, земляные, обучение, разрешения
        smr -= (145_000+0.6*118_000+58_000)*(0.5+0.5*k)
        eng  = ENG_rec*0.25*N**b(PF_ENG)
    direct = mat+lab+logi+smr+eng
    return direct*(1+cont_rate)
