"""Общий модуль эволюционной геометрии трека «Простая литая ГТУ-заменитель» (routes/gtu/evo/core).

Только гладкие представления формы (урок organic/structure: воксельные топологии проверку в CalculiX на гладкой
геометрии не прошли): неявные поверхности (SDF) со скруглениями, B-сплайны, деформация свободной формы (FFD),
решётки TPMS и Вороного с плавной плотностью, ветвящиеся каналы по закону Мюррея и L-системам, сплайновые лопатки
с законами закрутки и биомиметическими приёмами.

Модули:
    islands   — сиды островов, деление островов на части по номеру острова, прогон части, слияние архивов с контролем полноты
    archive   — MAP-Elites: сетка дескрипторов, архив, операторы изменчивости (гаусс, iso+line, SBX, полиномиальная мутация)
    nsga2     — NSGA-II с ограничениями (правила допустимости Деба), гиперобъём, ZDT1
    cmaes     — CMA-ES (ask/tell) с границами [0, 1]
    shapes    — B-сплайны и кривизна, SDF и гладкие операции, TPMS, Вороной, FFD, дерево Мюррея, L-система
    checks    — вокселизация SDF, наименьшая стенка, нависания, выход порошка, самопересечения
    mesh      — поверхность по SDF (surface nets), оболочка вращения с рельефом, трубки, STL
    blade     — сплайновая лопатка: закрутка, навал/изгиб/стреловидность, бугорки, серрации, риблеты
    features  — признаки «эффектности»: новизна, гладкость, сложность силуэта, симметрия
    render    — эскизы элит: три ракурса, монохром, лист «как эскизы воронки»
    sources   — источники приёмов и методов (статус каждого)

Геном любого семейства — вектор в единичном кубе [0, 1]^d; семейство само переводит его в форму (decode).
Всё детерминировано: одинаковые сид и конфигурация — одинаковый архив при любом числе процессов и частей.
"""
__all__ = ["islands", "archive", "nsga2", "cmaes", "shapes", "checks", "mesh", "blade", "features", "render", "sources"]
