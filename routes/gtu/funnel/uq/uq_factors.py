def lhs(n, d, seed):
    """латинский гиперкуб n × d (numpy PCG64): в каждом столбце - по одной точке в каждом из n слоёв, порядок слоёв - случайная
    перестановка, положение внутри слоя - равномерно. Первые n/2 строк - случайная подвыборка (строки перемешаны) - на ней
    проверяется сходимость без отдельного расчёта"""
    rng = np.random.Generator(np.random.PCG64(int(seed)))
    u = np.empty((n, d))
    for k in range(d):
        u[:, k] = (rng.permutation(n) + rng.random(n)) / n
    return u


def _inv(dist, par, u):
    u = min(max(float(u), 1e-12), 1.0 - 1e-12)
    if dist == "unif":
        lo, hi = par
        return lo + (hi - lo) * u
    if dist == "tri":
        a, c, b = par
        fc = (c - a) / (b - a)
        return a + math.sqrt(u * (b - a) * (c - a)) if u < fc else b - math.sqrt((1 - u) * (b - a) * (b - c))
    if dist == "norm":
        mu, sd, lo, hi = par
        pa, pb = ndtr((lo - mu) / sd), ndtr((hi - mu) / sd)
        return float(mu + sd * ndtri(pa + u * (pb - pa)))
    if dist == "lognorm":
        s, lo, hi = par
        pa, pb = ndtr(math.log(lo) / s), ndtr(math.log(hi) / s)
        return float(math.exp(s * ndtri(pa + u * (pb - pa))))
    if dist == "disc":
        vals, ps = par
        acc = 0.0
        for v, p in zip(vals, ps):
            acc += p
            if u <= acc + 1e-12:
                return v
        return vals[-1]
    raise ValueError(dist)


def values(urow):
    """строка гиперкуба -> значения факторов"""
    return {name: _inv(dist, par, urow[k]) for k, (name, grp, dist, par, nom, unit, what, basis) in enumerate(FACTORS)}


