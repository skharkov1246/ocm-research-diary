"""Воронка двигателя-заменителя, уровень 0: Plug&Play в существующий пакет -> балл 0-10.

Интерфейсы - чек-лист навыка gtu-dropin (раздел 3): выходной вал и муфта, опоры и рама, вход, выхлоп, масло, топливо,
пуск, САУ, укрытие (пожаротушение и вентиляция), подъём и выкатка. Каждый получает состояние:
    «сохраняется» 1,0 - пакет не трогают;
    «переходник»  0,6 - переходная деталь или перенастройка, пакет не переделывают;
    «нет данных»  0,6 - сравнить не с чем (данных исходной установки нет); помечается в no_data;
    «переделка»   0,2 - пакет переделывают (новый стартёр, новая логика САУ, новая рама);
    «невозможно»  0,0 - вне мягкого допуска или частота вала не та: blocked, балл 0.
Мягкий допуск (решение владельца 14.11.2026, README трека): расход через вход и выхлоп до +20 %, температура выхлопа
до +100 °C. Внутри допуска состояние вход/выхлоп падает линейно от 1,0 (не больше исходного) до 0,6 (на границе).
Балл: S = 10 * Σ w_i * s_i (веса WEIGHTS, сумма 1); при blocked S = 0.
Потери тракта (gtu-dropin, раздел 5): вход Δp ~ (G/G0)^2; выхлоп Δp ~ (G/G0)^2 * (t+273,15)/(t0+273,15).
v3, ось «корпус» (решение владельца 15.11.2026, п. 3): у оболочки модуль замены - двигатель целиком; это входит в «подъём и выкатку»
через массу самого тяжёлого модуля (module_kg_max против массы исходного двигателя), отдельного правила нет - стыки с пакетом
(вал, рама, вход, выхлоп, масло, топливо) у обоих значений оси одни и те же.
"""

STATE = {"сохраняется": 1.0, "переходник": 0.6, "нет данных": 0.6, "переделка": 0.2, "невозможно": 0.0}
WEIGHTS = {"вал и муфта": 0.15, "опоры и рама": 0.10, "вход": 0.10, "выхлоп": 0.15, "масло": 0.10, "топливо": 0.10,
           "пуск": 0.10, "САУ": 0.10, "укрытие": 0.05, "подъём и выкатка": 0.05}
SOFT = dict(alpha=0.20, dT=100.0)
FUEL_FLOW_TOL = 0.10        # прирост расхода топлива без пересчёта клапанов (оценка)
FUEL_P_TOL = 1.20           # π больше исходной в 1,2 раза - нужен дожимной компрессор газа (оценка)


def _lin(x, x0, x1):
    """1,0 при x <= x0, 0,6 при x = x1, линейно; x > x1 -> 0"""
    if x <= x0:
        return 1.0
    if x > x1 + 1e-9:
        return 0.0
    return 1.0 - 0.4 * (x - x0) / (x1 - x0)


def _state_of(v):
    return "сохраняется" if v >= 0.999 else ("невозможно" if v <= 0.0 else "переходник")


def score(pp):
    S, note, no_data = {}, {}, []

    # вал и муфта: частота выходного вала = частота входа редуктора или приводной машины пакета
    if abs(pp["n_out"] - pp["n_pkg"]) / pp["n_pkg"] > 0.005:
        S["вал и муфта"] = (0.0, "невозможно"); note["вал и муфта"] = f"частота {pp['n_out']:.0f} против {pp['n_pkg']:.0f} об/мин"
    else:
        S["вал и муфта"] = (1.0, "сохраняется")
        note["вал и муфта"] = "частота и фланец как у исходного; крутильный расчёт валопровода - заново (gtu-dropin)"

    # опоры и рама
    if pp["D_env"] > min(pp["pkg_W"], pp["pkg_H"]):
        S["опоры и рама"] = (0.0, "невозможно"); note["опоры и рама"] = "габарит больше ширины или высоты пакета"
    elif pp["cores"] > 1:
        S["опоры и рама"] = (0.2, "переделка"); note["опоры и рама"] = f"рама под {pp['cores']} ядра и силовую турбину"
    elif pp["recup"] and not pp.get("recup_integral"):
        S["опоры и рама"] = (0.2, "переделка"); note["опоры и рама"] = "опоры вынесенного рекуператора"
    else:
        S["опоры и рама"] = (0.6, "переходник"); note["опоры и рама"] = "переходная рама под новые точки опор"

    # вход
    g = pp["G"] / pp["G0"]
    v = _lin(g, 1.0, 1.0 + SOFT["alpha"])
    st = _state_of(v)
    if st != "невозможно" and (pp["inlet"] == "двух" or pp["cores"] > 1):
        v, st = min(v, 0.6), "переходник"
    S["вход"] = (v, st); note["вход"] = f"расход x{g:.3f}, потери входа x{g * g:.3f}"

    # выхлоп
    t1, t0 = pp["EGT"], pp["EGT0"]
    vt = _lin(t1 - t0, 0.0, SOFT["dT"])
    v = min(_lin(g, 1.0, 1.0 + SOFT["alpha"]), vt)
    dp = g * g * (t1 + 273.15) / (t0 + 273.15)
    S["выхлоп"] = (v, _state_of(v)); note["выхлоп"] = f"выхлоп {t1:.0f} против {t0:.0f} °C; потери выхлопа x{dp:.3f}"

    # масло
    if pp["bear"] == "магнит":
        S["масло"] = (1.0, "сохраняется"); note["масло"] = "двигателю масло не нужно; маслосистема пакета - для редуктора"
    elif pp["cores"] > 1:
        S["масло"] = (0.2, "переделка"); note["масло"] = f"подвод к {pp['cores']} ядрам и силовой турбине"
    elif pp["rotors"] > pp["rotors0"]:
        S["масло"] = (0.6, "переходник"); note["масло"] = "второй ротор: больше подшипников и тепла в масло"
    else:
        S["масло"] = (1.0, "сохраняется"); note["масло"] = "столько же роторов, масло пакета"

    # топливо
    if pp["comb"] in ("RDC", "ВР"):
        S["топливо"] = (0.2, "переделка"); note["топливо"] = "другая подача и регулирование топлива"
    else:
        fuel = (pp["eta0"] / pp["eta"] - 1.0) if (pp.get("eta0") and pp.get("eta")) else None
        pr = pp["pi"] / pp["pi0"] if pp.get("pi0") else None
        if pr is None or fuel is None:
            S["топливо"] = (0.6, "нет данных"); no_data.append("топливо")
        elif pr > FUEL_P_TOL:
            S["топливо"] = (0.2, "переделка"); note["топливо"] = f"π в {pr:.2f} раза выше исходной: давление газа пакета не хватит"
        elif pr > 1.0 or fuel > FUEL_FLOW_TOL:
            S["топливо"] = (0.6, "переходник"); note["топливо"] = f"π x{pr:.2f}, расход топлива {fuel * 100:+.0f} %: пересчёт клапанов"
        else:
            S["топливо"] = (1.0, "сохраняется"); note["топливо"] = f"π x{pr:.2f}, расход топлива {fuel * 100:+.0f} %"

    # пуск
    if pp["cores"] > 1:
        S["пуск"] = (0.2, "переделка"); note["пуск"] = "стартёр на каждое ядро"
    elif pp["rotors"] > pp["rotors0"]:
        S["пуск"] = (0.2, "переделка"); note["пуск"] = "стартёр пакета на стороне редуктора: газогенератору нужен свой"
    else:
        S["пуск"] = (0.6, "нет данных"); no_data.append("пуск")
        note["пуск"] = "момент инерции исходного ротора неизвестен: момент стартёра проверить"

    # САУ
    if pp["comb"] in ("RDC", "ВР") or pp["cores"] > 1 or pp["bear"] == "магнит" or pp["rotors"] > pp["rotors0"]:
        why = [w for w, c in (("новая камера", pp["comb"] in ("RDC", "ВР")), ("кластер", pp["cores"] > 1),
                              ("магнитные подшипники", pp["bear"] == "магнит"), ("второй ротор", pp["rotors"] > pp["rotors0"])) if c]
        S["САУ"] = (0.2, "переделка"); note["САУ"] = ", ".join(why)
    else:
        S["САУ"] = (0.6, "переходник"); note["САУ"] = "новые уставки и законы в штатной системе" + (" + обвод рекуператора" if pp["recup"] else "")

    # укрытие
    if pp["comb"] == "RDC":
        S["укрытие"] = (0.2, "переделка"); note["укрытие"] = "шум и вибрация детонационного горения (оценка)"
    elif pp["recup"] and not pp.get("recup_integral"):
        S["укрытие"] = (0.2, "переделка"); note["укрытие"] = "вынесенный рекуператор: место и тепло в укрытии"
    elif pp["recup"]:
        S["укрытие"] = (0.6, "переходник"); note["укрытие"] = "больше горячей поверхности: проверить вентиляцию"
    else:
        S["укрытие"] = (1.0, "сохраняется")

    # подъём и выкатка
    if pp.get("engine_kg0"):
        if pp["module_kg_max"] <= pp["engine_kg0"]:
            S["подъём и выкатка"] = (1.0, "сохраняется")
        else:
            S["подъём и выкатка"] = (0.2, "переделка"); note["подъём и выкатка"] = "модуль тяжелее исходного двигателя"
    else:
        S["подъём и выкатка"] = (0.6, "нет данных"); no_data.append("подъём и выкатка")
    note.setdefault("подъём и выкатка", f"самый тяжёлый модуль {pp['module_kg_max']:.0f} кг (оценка)")
    if pp.get("case_arch") == "оболочка":
        note["подъём и выкатка"] += "; оболочка: на объекте меняется двигатель целиком"

    blocked = [k for k, (v, s) in S.items() if s == "невозможно"]
    total = 0.0 if blocked else 10.0 * sum(WEIGHTS[k] * v for k, (v, s) in S.items())
    return dict(score=round(total, 3), blocked=blocked, no_data=no_data,
                items={k: dict(state=s, value=round(v, 3), weight=WEIGHTS[k], note=note.get(k, "")) for k, (v, s) in S.items()})
