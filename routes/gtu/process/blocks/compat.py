WHY = {r["id"]: r["why"] for r in TABLE}


def check_static(C, tgt):
    R = []
    R += compressor.static_rules(C)
    R += turbine.static_rules(C)
    R += hx.static_rules(C)
    R += shaft.static_rules(C, tgt)
    cb, hxc, fu = C["combustor"], C["hx"], C["fuel"]
    pgc = cb["scheme"] in ("RDC", "ВР")
    if pgc and hxc["recup"]:
        R.append(dict(code="pgc_recup", hard=False, ok=False, text=WHY["pgc_recup"]))
    if pgc and C["turbine"]["cool"] == "U":
        R.append(dict(code="pgc_cool_U", hard=False, ok=False, text=WHY["pgc_cool_U"]))
    if fu["prep"] == "паровой риформинг":
        R.append(dict(code="pnp_water", hard=False, ok=False, text=WHY["pnp_water"]))
    if fu["prep"] == "сухой риформинг":
        R.append(dict(code="egr_o2", hard=False, ok=False, text=WHY["egr_o2"]))
    for r in R:
        r.setdefault("group", "совместимость")
    return R
