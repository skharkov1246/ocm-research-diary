# -*- coding: utf-8 -*-
"""
Рычаг: снятие HS 2837.11 с Mining List (5%) + Import Adjustment Tax ЭКОВАС.
Пересчёт эффекта в $/т NaCN, в NPV и в сроке окупаемости.
Все входные числа помечены; источник — предыдущая работа проекта
(routes/nacn_s1/final_econ_out.txt, duty_ghana_out.txt) и первичные тарифы.
"""

CIF          = 2036.0   # [П] средняя CIF Тема 2025, HS 283711
GATE_LO, GATE_HI = 2161.0, 2253.0  # [О] CIF + доведение до ворот 125-217, БЕЗ пошлины
CAPEX        = 10.22e6  # [О] рекомендуемая конфигурация
Q            = 2500.0   # т/год
C_LO, C_HI   = 1661.0, 2372.0      # [О] денежная себестоимость
DEM_LO, DEM_HI = 18000.0, 20000.0  # [П] внутреннее потребление Ганы
IMPORTS      = 32327.0  # [П] ввоз 2025

# --- стек сборов при импорте (доли CIF) -------------------------------------
d_now   = 0.05   # [Т] Mining List, льготная ставка для держателя горного права
d_cet   = 0.10   # [Т] базовая CET для 2837.11 — тарифная строка НЕ подтверждена
lev_oth = 0.005 + 0.002 + 0.0075 + 0.010   # ECOWAS 0.5 + AU 0.2 + EXIM 0.75 + ICUMS 1.0 [Т]
vat_stack = 0.15 + 0.025 + 0.025           # [П] Act 1151 с 01.01.2026

def duty(rate):  return CIF * rate
def landed(rate): return CIF * (1.0 + rate + lev_oth)

print("="*86)
print("1. СТЕК СБОРОВ И СДВИГ ПАРИТЕТА")
print("="*86)
scen = [("статус-кво: Mining List 5%",           0.05),
        ("(а) снятие с Mining List -> CET 10%",  0.10),
        ("(а)+(б) CET 10% + IAT 10% = 20%",      0.20),
        ("(а)+(б) CET 10% + IAT 20% = 30%",      0.30)]
base = duty(0.05)
for name, r in scen:
    D = duty(r)
    # отвлечение оборотных средств руднику: VAT считается от базы, включающей пошлину
    vat_carry_lo = (D - base) * vat_stack * 0.15 * 0.25   # 3 мес под 15% годовых
    vat_carry_hi = (D - base) * vat_stack * 0.15 * 0.75   # 9 мес
    print(f"{name:38s} пошлина {D:8.2f}  Δ к статус-кво {D-base:8.2f}"
          f"  + отвлечение VAT {vat_carry_lo:5.2f}..{vat_carry_hi:5.2f}"
          f"  ИТОГО Δ {D-base+vat_carry_lo:8.2f}..{D-base+vat_carry_hi:8.2f}")

dA = duty(0.10)-base
dB = duty(0.20)-base
dC = duty(0.30)-base
print(f"\nПроверка авторского счёта: 10% от CIF = {CIF*0.10:.2f}; 20% = {CIF*0.20:.2f}")
print("Автор считает только надбавку IAT и не считает шаг 5%->10%, который сам же предлагает.")

print()
print("="*86)
print("2. ЭФФЕКТИВНАЯ СТАВКА ЗАЩИТЫ (ERP) — ПЕРЕСЧЁТ")
print("="*86)
# торгуемые входы, $/т NaCN, по мировым (=CIF) ценам
inp = {"мочевина": (541.0, 0.00), "едкий натр стехиом.": (512.0, 0.10),
       "едкий натр на CO2": (84.0, 0.10), "катализатор Pt/Rh": (62.0, 0.00)}
world_in = sum(v[0] for v in inp.values())
VA_w = CIF - world_in
def erp(t_out, caustic_duty):
    dom_out = CIF * (1 + t_out)
    dom_in = sum(v[0]*(1 + (caustic_duty if v[1] > 0 else 0.0)) for v in inp.values())
    return (dom_out - dom_in - VA_w) / VA_w * 100.0
print(f"торгуемые входы по мировым ценам {world_in:.1f} $/т; добавленная стоимость {VA_w:.1f} $/т")
print(f"сейчас (выпуск 5%, щёлочь 10%) ............ ERP = {erp(0.05,0.10):6.2f}%")
print(f"обнуление пошлины на щёлочь ............... ERP = {erp(0.05,0.00):6.2f}%")
print(f"выпуск 20% (CET10+IAT10) + щёлочь 0% ...... ERP = {erp(0.20,0.00):6.2f}%")
print(f"выпуск 30% (CET10+IAT20) + щёлочь 0% ...... ERP = {erp(0.30,0.00):6.2f}%")

print()
print("="*86)
print("3. ОКУПАЕМОСТЬ")
print("="*86)
def pb(P, c):
    m = (P - c) * Q
    return CAPEX/m if m > 0 else float('inf')
for P0, tag in [(2207.0, "паритет (середина 2161-2253)"),
                (2757.0, "целевой сегмент (середина greenfield 2410-3104)")]:
    print(f"\nбазовая цена {P0:.0f} $/т — {tag}")
    for nm, d in [("без рычага", 0.0), ("(а) только Mining List", dA),
                  ("(а)+IAT 10%", dB), ("(а)+IAT 20%", dC)]:
        P = P0 + d
        a, b = pb(P, C_LO), pb(P, C_HI)
        sa = f"{a:5.2f}" if a < 99 else "  n/a"
        sb = f"{b:5.2f}" if b < 99 else "  n/a"
        print(f"  {nm:24s} цена {P:7.1f}  окупаемость {sa} г (низ. с/с) / {sb} г (верх. с/с)")

print()
print("="*86)
print("4. ДЕНЬГИ ПРОЕКТА И NPV РЫЧАГА")
print("="*86)
r = 0.12
af5 = sum(1/(1+r)**k for k in range(1,6))
print(f"аннуитетный фактор 5 лет @12% = {af5:.4f}")
perp = dA*Q/r
print(f"(а) Mining List: {dA:.1f} $/т x {Q:.0f} т = {dA*Q/1e3:.1f} тыс.$/год, бессрочно -> NPV {perp/1e6:.2f} млн$")
for nm, dI in [("IAT 10%", CIF*0.10), ("IAT 20%", CIF*0.20)]:
    print(f"{nm}: {dI:.1f} $/т x {Q:.0f} т = {dI*Q/1e3:.1f} тыс.$/год, лимит ЭКОВАС 5 лет -> NPV {dI*Q*af5/1e6:.2f} млн$")
    print(f"   суммарный NPV рычага (а)+({nm}) = {(perp + dI*Q*af5)/1e6:.2f} млн$")

print()
print("="*86)
print("5. НАЦИОНАЛЬНАЯ ЦЕНА ВОПРОСА И ПОЗИЦИЯ РУДНИКА-ХОЗЯИНА")
print("="*86)
for nm, d in [("(а) только", dA), ("(а)+IAT10", dB), ("(а)+IAT20", dC)]:
    print(f"{nm:12s} доплата рудников страны: {DEM_LO*d/1e6:5.2f}-{DEM_HI*d/1e6:5.2f} млн$/год")
print("(реэкспорт 37-44% идёт транзитом/со склада и пошлину не платит — база = только внутр. потребление)")
for Qm in (6000.0, 8000.0):
    for nm, d in [("(а)+IAT10", dB), ("(а)+IAT20", dC)]:
        extra = (Qm - Q) * d
        gain  = Q * d
        print(f"  рудник-хозяин {Qm:.0f} т/год, {nm}: доплата за импортный остаток {extra/1e3:6.1f} тыс.$"
              f" + нам {gain/1e3:6.1f} тыс.$ => нетто-убыток рудника {(extra+gain-gain)/1e3:6.1f}"
              f" тыс.$ сверх того, что он платит нам; полный рост его затрат {(extra+gain)/1e3:6.1f} тыс.$/год")

print()
print("="*86)
print("6. ВЕС ЦИАНИДА В ЭКОНОМИКЕ РУДНИКА — ПРОВЕРКА ВОЗРАЖЕНИЯ 'НАЛОГ НА ЗОЛОТО'")
print("="*86)
for cons in (0.4, 0.5, 0.6):          # кг NaCN / т руды [Д]
    for grade in (1.1, 1.5):          # г/т [Д]
        oz = grade*0.90/31.1035
        for nm, d in [("IAT10 итого +305", dB), ("IAT20 итого +509", dC)]:
            print(f"  расход {cons} кг/т, содержание {grade} г/т: NaCN {cons*2.2:.2f} $/т руды"
                  f" = {cons*2.2/oz:6.1f} $/унц; прирост {nm}: +{cons*d/1000/oz:5.2f} $/унц"
                  f" ({cons*d/1000/oz/1500*100:.2f}% AISC@1500)")
        break
    break

print()
