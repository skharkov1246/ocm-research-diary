print("оговорка 'автоматическая отмена, если местная мощность < 50% спроса' =>")
print(f"  порог срабатывания {0.5*DEM_LO:.0f}-{0.5*DEM_HI:.0f} т/год; наш завод даёт {Q/ (0.5*DEM_LO)*100:.1f}% этого порога.")
print("  => норма НИКОГДА не вступит в силу при единственном заводе на 2500 т.")

