h("2. ПОЛНЫЙ СТЕК СБОРОВ ПРИ ИМПОРТЕ, 2026 г.")
CIF=1800.0; T=2500.0
duty_r=0.05
lv={"ECOWAS Levy":0.005,"African Union Import Levy (Act 952)":0.002,
    "EXIM Levy":0.0075,"Сбор за обработку/ICUMS":0.010}
print(f"База: CIF ${CIF:,.0f}/т, объём {T:,.0f} т/год\n")
print(f"{'сбор':<44}{'ставка':>10}{'$/т':>10}{'метка':>8}")
duty=CIF*duty_r
print(f"{'Импортная пошлина (Mining List, не-оборудование)':<44}{duty_r*100:>9.2f}%{duty:>10.0f}{'[В]':>8}")
tot_lv=0
for n,r in lv.items():
    v=CIF*r; tot_lv+=v
    tag="[П]" if "African" in n else "[Т]"
    print(f"{n:<44}{r*100:>9.2f}%{v:>10.0f}{tag:>8}")
base_vat=CIF+duty+tot_lv
print(f"{'-'*72}")
print(f"{'База для VAT (CIF + пошлина + сборы)':<44}{'':>10}{base_vat:>10.0f}")
vat_r,nhil_r,get_r=0.15,0.025,0.025
vat=base_vat*vat_r; nhil=base_vat*nhil_r; get=base_vat*get_r
print(f"{'VAT':<44}{vat_r*100:>9.1f}%{vat:>10.0f}{'[П]':>8}")
print(f"{'NHIL':<44}{nhil_r*100:>9.1f}%{nhil:>10.0f}{'[П]':>8}")
print(f"{'GETFund Levy':<44}{get_r*100:>9.1f}%{get:>10.0f}{'[П]':>8}")
print(f"{'-'*72}")
print(f"{'ИТОГО К УПЛАТЕ НА ТАМОЖНЕ':<44}{'':>10}{duty+tot_lv+vat+nhil+get:>10.0f}")
print(f"{'из них НЕВОЗВРАТНО (пошлина + сборы)':<44}{'':>10}{duty+tot_lv:>10.0f}")
print(f"{'из них зачитывается (VAT+NHIL+GETFund)':<44}{'':>10}{vat+nhil+get:>10.0f}")
print(f"""
Ключевая поправка, которую нельзя пропустить:
  Act 1151 (VAT Act, 2025), в силе с 01.01.2026 [П, разбор EY]:
   - ставка VAT унифицирована 15%, NHIL и GETFund по 2.5% сохранены;
   - NHIL и GETFund СТАЛИ вычитаемыми как входящий налог;
   - COVID-19 Health Recovery Levy отменён;
   - НО каскадный эффект NHIL и GETFund 'appears to subsist for import of goods'.
  Итог: 20% на таможне для зарегистрированного плательщика — это НЕ затрата,
  а отвлечение оборотных средств. Затрата — только пошлина и сборы.""")

h("3. ЛЬГОТА ПО VAT — ЕЁ У ДЕЙСТВУЮЩЕГО РУДНИКА НЕТ")
print("""Третье приложение Act 1151 [П]: от VAT освобождается поставка товаров и услуг
'in connection with RECONNAISSANCE OR PROSPECTING by a holder of a reconnaissance
licence or prospecting licence'. Это разведка. Действующий рудник с mining lease
под льготу НЕ подпадает и цианид покупает с полным VAT.

Дополнительно: экспорт золота облагается по нулевой ставке, значит у рудника
структурно постоянный избыток входящего налога, который возвращается только
через процедуру возврата. EY прямо называет это 'pay then claim' и указывает
на нагрузку на оборотный капитал. Это не гипотеза, это опубликованный разбор
нового закона.""")
delay_m=(3,9)
vat_carry=(vat+nhil+get)*delay_m[0]/12*0.15,(vat+nhil+get)*delay_m[1]/12*0.15
print(f"\nСтоимость задержки возврата {delay_m[0]}-{delay_m[1]} мес. под 15% годовых:")
print(f"   ${vat_carry[0]:.0f}-{vat_carry[1]:.0f}/т [О] — это НЕ было учтено в TCO-модели,")
print(f"   добавляется к статье 'оборотный капитал'.")

h("4. ЧТО МЕНЯЕТ ПРОИЗВОДСТВО НА МЕСТЕ — СЧИТАЕМ ПО ЦЕПОЧКЕ")
print("Локальный завод не отменяет пошлины, он ПЕРЕНОСИТ их с готового продукта")
print("на сырьё. Считаем разницу баз.\n")
nh3_k,naoh_k=0.4989,0.8323
nh3_p,naoh_p=600.0,400.0
imp_val=CIF*T
loc_val=(nh3_k*nh3_p+naoh_k*naoh_p)*T
print(f"{'':<40}{'т/год':>10}{'$/т':>9}{'база, $/год':>15}")
print(f"{'ИМПОРТ ГОТОВОГО NaCN':<40}{T:>10,.0f}{CIF:>9,.0f}{imp_val:>15,.0f}")
print(f"{'  аммиак':<40}{nh3_k*T:>10,.0f}{nh3_p:>9,.0f}{nh3_k*nh3_p*T:>15,.0f}")
print(f"{'  едкий натр':<40}{naoh_k*T:>10,.0f}{naoh_p:>9,.0f}{naoh_k*naoh_p*T:>15,.0f}")
print(f"{'  метан — местный, границу не пересекает':<40}{'':>10}{'':>9}{0:>15,.0f}")
print(f"{'ИМПОРТ СЫРЬЯ ДЛЯ ЛОКАЛЬНОГО ЗАВОДА':<40}{'':>10}{'':>9}{loc_val:>15,.0f}")
print(f"\nОблагаемая база сжимается в {imp_val/loc_val:.1f} раза.")
for rate in (0.05,0.10):
    d_imp=imp_val*rate; d_loc=loc_val*rate
    print(f"  при ставке {rate*100:.0f}%: пошлина ${d_imp/1e3:,.0f} тыс. -> ${d_loc/1e3:,.0f} тыс./год,")
    print(f"     экономия ${(d_imp-d_loc)/1e3:,.0f} тыс./год = ${(d_imp-d_loc)/T:,.0f}/т NaCN")
print("""
Плюс сборы (ECOWAS+AU+EXIM+обработка = 2.45% базы) сжимаются в той же пропорции.""")
lev_save=(imp_val-loc_val)*sum(lv.values())
print(f"  экономия на сборах: ${lev_save/1e3:,.0f} тыс./год = ${lev_save/T:,.0f}/т")
tot_save=(imp_val-loc_val)*(0.05+sum(lv.values()))
print(f"\n  ИТОГО ЭКОНОМИЯ НА ТАМОЖНЕ ПО ЦЕПОЧКЕ: ${tot_save/1e3:,.0f} тыс./год = ${tot_save/T:,.0f}/т NaCN")
print("  Кому она достаётся, решает контракт. В переговорах это ещё один")
print("  измеримый аргумент в пользу цены выше паритета с импортом.")

