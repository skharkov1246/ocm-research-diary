# -*- coding: utf-8 -*-
"""
СВОЁ СЫРЬЁ ВМЕСТО ПРИВОЗНОГО: три маршрута, посчитанные до числа.
[П] первичный источник  [О] расчёт  [Д] допущение, нужна проверка
"""
L="="*94
def h(t): print("\n"+L+"\n"+t+"\n"+L)
T=2500.0
NAOH=(0.857*T, 0.90*T)        # т 100% NaOH/год
NH3=(0.511*T, 0.589*T)        # т NH3/год
P_naoh=597.0; P_urea=545.0
u_lo,u_hi=0.929,1.071

h("0. ЧТО В ГАНЕ ДЕЙСТВИТЕЛЬНО МЕСТНОЕ")
print("""  Соль. Концессия Ада-Сонгор (Electrochem), 41 000 акров: пуск 2021,
        мощность 1 млн т/год соли чистотой 99.9%, предел концессии 15 млн т/год.
        По стране сейчас ~250 тыс. т/год. Президент прямо называл её основой
        будущей нефтехимии. Это ровно то сырьё, которое нужно хлор-щелочному
        производству, и оно есть. [П]
  Известь. Позиция 4 перечня обязательных локальных закупок (L.I. 2431).
        Рудники уже покупают её тоннами для регулирования pH. [П]
  Природный газ. Труба Genser, завод в Престеа с 2026. [П]
  Известняк, вода, воздух.
  И ЕЩЁ ОДНО, ЧТО МЫ СЕЙЧАС СЖИГАЕМ: хвостовой газ после абсорбера содержит
        9.76 кмоль/ч водорода. Это 65% от того, что нужно для синтеза
        собственного аммиака. Сейчас он идёт в термоокислитель. [О]""")

h("1. МАРШРУТ А — СВОЯ ЩЁЛОЧЬ ИЗ МЕСТНОЙ СОЛИ (мембранный электролиз)")
salt_t=1.5; kwh_t=2360.0
P_salt=(60.,110.); P_pwr=(0.1481,0.1914)
print(f"2 NaCl + 2 H2O -> 2 NaOH + Cl2 + H2")
print(f"  потребность в щёлочи............ {NAOH[0]:,.0f}-{NAOH[1]:,.0f} т/год 100%")
print(f"  соли (1.5 т/т)................. {NAOH[0]*salt_t:,.0f}-{NAOH[1]*salt_t:,.0f} т/год")
print(f"  электроэнергии (2360 кВт*ч/т)... {NAOH[0]*kwh_t/1e6:.2f}-{NAOH[1]*kwh_t/1e6:.2f} ГВт*ч/год")
print(f"                                  = {NAOH[0]*kwh_t/8000:.0f}-{NAOH[1]*kwh_t/8000:.0f} кВт непрерывно")
print(f"  для сравнения: вся установка NaCN потребляет ~160 кВт")
print(f"\n  СЕБЕСТОИМОСТЬ ТОННЫ СОБСТВЕННОЙ ЩЁЛОЧИ:")
for ps in P_salt:
    for pp in P_pwr:
        c=salt_t*ps+kwh_t*pp+100.0
        print(f"    соль ${ps:.0f}/т, ток ${pp:.4f}/кВт*ч: {salt_t*ps:>5.0f} + {kwh_t*pp:>5.0f} + 100 (мембраны,")
        print(f"      рассолоподготовка, ТОиР) = ${c:>5.0f}/т против покупной ${P_naoh:.0f}/т -> {'экономия' if c<P_naoh else 'ДОРОЖЕ'} ${abs(c-P_naoh):.0f}")
print(f"""
  ТОЧКА БЕЗУБЫТОЧНОСТИ ПО ЦЕНЕ ТОКА: ${(P_naoh-salt_t*85-100)/kwh_t:.4f}/кВт*ч.
  Тариф bulk customer в Гане ${P_pwr[0]:.4f}, розничный SLT-MV ${P_pwr[1]:.4f}.
  То есть мы стоим ровно НА границе и при розничном тарифе уходим в минус.
  Мировые хлор-щелочные заводы платят за ток $0.03-0.05/кВт*ч — там щёлочь
  стоит ${salt_t*40+kwh_t*0.04+80:.0f}/т. Вот почему в Гане нет хлор-щелочного производства:
  дело не в соли, соли достаточно, дело в цене электроэнергии.""")
cl2=(NAOH[0]*0.886,NAOH[1]*0.886); h2=(NAOH[0]*0.025,NAOH[1]*0.025)
print(f"""
  И ГЛАВНОЕ — ПОБОЧНЫЙ ХЛОР. На нашу щёлочь его выходит {cl2[0]:,.0f}-{cl2[1]:,.0f} т/год.
  Хлор — класс 2.3, токсичный газ при вдыхании: опаснее цианида по способу
  поражения, потому что распространяется сам. Деть его некуда:
    продать — рынка у рудника нет;
    сжечь в HCl — получим {cl2[0]*1.029:,.0f} т/год соляной кислоты, а мы весь
      анализ безопасности потратили на то, чтобы кислоты на площадке не было;
    в гипохлорит — рынок обезвреживания цианида на порядок меньше.
  ВЕРДИКТ: маршрут А убивает себя дважды — ценой тока и хлором.
  Собственная щёлочь в Гане экономически нейтральна и создаёт вещество
  опаснее того, ради которого всё затевалось.""")

h("2. МАРШРУТ Б — СВОЙ АММИАК, И ТОГДА МОЧЕВИНА ВООБЩЕ НЕ НУЖНА")
print("""Мочевину мы выбрали не потому, что она хороша, а потому, что аммиака
в Гане нет как товара. Если делать аммиак самим, урейный узел исчезает
целиком — вместе с балластом CO2, гидролизёром на 39 бар, подогревателем
воздуха до 415 C и перерасходом щёлочи на со-абсорбцию.""")
GJ=(35.,55.); GAS=(3.80,11.0)
print(f"\n  потребность в аммиаке........... {NH3[0]:,.0f}-{NH3[1]:,.0f} т/год = {NH3[0]/365:.1f}-{NH3[1]/365:.1f} т/сут")
print(f"  удельный расход газа на NH3..... {GJ[0]:.0f}-{GJ[1]:.0f} ГДж/т (паровая конверсия)")
mm=(NH3[0]*GJ[0]/1.055,NH3[1]*GJ[1]/1.055)
print(f"  дополнительный газ.............. {mm[0]:,.0f}-{mm[1]:,.0f} MMBtu/год")
print(f"  его стоимость................... ${mm[0]*GAS[0]/1e3:,.0f}-{mm[1]*GAS[1]/1e3:,.0f} тыс./год")
print(f"                                  = ${mm[0]*GAS[0]/T:.0f}-{mm[1]*GAS[1]/T:.0f}/т NaCN")
urea_cost=(u_lo*P_urea,u_hi*P_urea)
print(f"  ОТМЕНЯЕТСЯ покупка мочевины..... ${urea_cost[0]:.0f}-{urea_cost[1]:.0f}/т NaCN")
sav=(urea_cost[0]-mm[1]*GAS[1]/T, urea_cost[1]-mm[0]*GAS[0]/T)
print(f"  ЧИСТАЯ ЭКОНОМИЯ ПО СЫРЬЮ........ ${sav[0]:.0f}...${sav[1]:.0f}/т NaCN")
print(f"                                  = ${sav[0]*T/1e3:,.0f}...${sav[1]*T/1e3:,.0f} тыс./год")
print("""
  СИНЕРГИЯ, КОТОРУЮ ВИДНО ТОЛЬКО ИЗНУТРИ ПРОЦЕССА: хвостовой газ уже содержит
  9.76 кмоль/ч водорода, а синтезу аммиака нужно 15.0 кмоль/ч. То есть 65%
  водорода у нас УЖЕ ЕСТЬ и сейчас сжигается. Паровой конверсии остаётся
  добрать треть, а не всё.""")
capex_nh3=(4.4e6,11.7e6)
print(f"""
  ЧЕГО ЭТО СТОИТ. Агрегат на {NH3[0]/365:.1f} т/сут — это одна сотая минимального
  промышленного размера. Синтез идёт при 150-250 бар, нужны конверсия,
  сдвиг, короткоцикловая адсорбция, холодильный контур. Оценка капитала
  ${capex_nh3[0]/1e6:.1f}-{capex_nh3[1]/1e6:.1f} млн [Д] — то есть сопоставимо со всей цианидной установкой.""")
for c in capex_nh3:
    print(f"    капитал ${c/1e6:.1f} млн при экономии ${sav[0]*T/1e3:,.0f}-{sav[1]*T/1e3:,.0f} тыс./год -> окупаемость {c/(sav[1]*T):.1f}-{c/(sav[0]*T):.1f} лет")
print("""  ВЕРДИКТ: идея верная по направлению, но на этом масштабе капитал съедает
  выгоду. Работает только при дешёвом газе И нижней границе оценки капитала.
  Держим как опцию второй очереди, когда мощность вырастет.""")

h("3. МАРШРУТ В — НЕ ДЕЛАТЬ ЩЁЛОЧЬ, А НЕ НУЖДАТЬСЯ В НЕЙ")
print("""Щёлочь нужна только для одного: связать HCN в соль. Натрий здесь ничего
не делает — работает цианид-ион. А известь в Гане местная, лежит в перечне
обязательных локальных закупок и уже завозится рудником тоннами для pH.

  2 HCN + Ca(OH)2 -> Ca(CN)2 + 2 H2O

Это не изобретение: цианид кальция под маркой Aero выпускался промышленно
и применялся в золотодобыче. Содержал 48-50% в пересчёте на NaCN, остальное
соль и известь, растворялся в воде легко, а нерастворённый остаток извести
и графитного углерода на растворение золота и серебра не влиял. [П]""")
CaO=0.572; P_lime=(120.,200.)
lime_cost=(CaO*P_lime[0],CaO*P_lime[1])
naoh_cost=(0.857*P_naoh,0.90*P_naoh)
co2_pen=(0.094*P_naoh,0.188*P_naoh)
print(f"\n  {'позиция':<44}{'$/т NaCN-экв':>16}")
print(f"  {'едкий натр (стехиометрия)':<44}{naoh_cost[0]:>7.0f}-{naoh_cost[1]:<8.0f}")
print(f"  {'едкий натр на CO2 из мочевины':<44}{co2_pen[0]:>7.0f}-{co2_pen[1]:<8.0f}")
print(f"  {'ИТОГО щелочная статья сейчас':<44}{naoh_cost[0]+co2_pen[0]:>7.0f}-{naoh_cost[1]+co2_pen[1]:<8.0f}")
print(f"  {'известь 0.572 т CaO по ганской цене':<44}{lime_cost[0]:>7.0f}-{lime_cost[1]:<8.0f}")
sav_c=(naoh_cost[0]+co2_pen[0]-lime_cost[1], naoh_cost[1]+co2_pen[1]-lime_cost[0])
print(f"  {'ЭКОНОМИЯ':<44}{sav_c[0]:>7.0f}-{sav_c[1]:<8.0f}")
print(f"\n  В год это ${sav_c[0]*T/1e6:.2f}-{sav_c[1]*T/1e6:.2f} млн. Капитал: гашение извести и")
print(f"  шламовое хозяйство +$250-450 тыс., минус склад щёлочи −$80-120 тыс.")
print(f"  Это ЕДИНСТВЕННЫЙ из трёх маршрутов, который не требует второго завода —")
print(f"  меняется реагент в абсорбере, а не добавляется производство.")
print("""
  ПОБОЧНОЕ СЛЕДСТВИЕ, КОТОРОЕ РАБОТАЕТ НА НАС: после обезвреживания цианида
  натрий остаётся в растворе, а кальций выпадает карбонатом. Это снижает
  солесодержание хвостов и облегчает закрытие рудника. То есть кальциевый
  маршрут ещё и экологически чище по солевой нагрузке.

  И второе: рудник сегодня покупает ОТДЕЛЬНО цианид и ОТДЕЛЬНО известь на pH.
  Кальциевый раствор приносит и цианид, и щёлочность одной поставкой.

  ЧЕГО МЫ НЕ ЗНАЕМ И ЧЕМ ЭТО МОЖЕТ КОНЧИТЬСЯ:
   1. Предельная концентрация раствора Ca(CN)2. Если она заметно ниже 30%,
      придётся качать больше воды: больше трубы, больше насосов, больше
      объёма в цикле выщелачивания. ЭТО ГЛАВНЫЙ РИСК МАРШРУТА.
   2. Гипсование. Кальций с сульфатом даёт CaSO4 — накипь в трубопроводах
      и в цикле. Зависит от состава конкретной руды и оборотной воды.
   3. Металлурги рудника консервативны: нестандартный реагент потребует
      промышленных испытаний на их руде и, скорее всего, дисконта на первый
      контракт.
  Ни одно из трёх нельзя закрыть расчётом — нужны лабораторные данные
  и колонное испытание.""")
print(f"  Цена вопроса ${sav_c[0]*T/1e6:.2f}-{sav_c[1]*T/1e6:.2f} млн в год оправдывает испытание в первую очередь.")
print()
print("  ПРОВЕРКА НА УСТОЙЧИВОСТЬ: цены на известь в Гане у меня из источника НЕТ,")
print("  взят диапазон $120-200/т [Т]. Проверяю, ломается ли вывод при худшей цене:")
for pl in (120.,200.,250.,300.,400.):
    c=CaO*pl
    print(f"    известь ${pl:.0f}/т -> ${c:.0f}/т NaCN, экономия против щёлочи ${naoh_cost[0]+co2_pen[0]-c:.0f}-{naoh_cost[1]+co2_pen[1]-c:.0f}")
print("  Вывод не переворачивается даже при извести втрое дороже принятой:")
print("  щёлочь стоит $597/т, известь дала бы ту же щёлочность дороже $1000/т CaO.")

h("4. ЧТО ЭТО ДАЁТ В СУММЕ")
lo0,hi0=1661.,2372.
co2_lime=(1.17*56.08/1e3*P_lime[0], 2.35*56.08/1e3*P_lime[1])  # CO2 связывается известью, а не щёлочью
print(f"Поправка: балласт CO2 из мочевины связывается той же известью, а не щёлочью:")
print(f"  1.17-2.35 кмоль CO2 на т NaCN -> {1.17*56.08/1e3:.3f}-{2.35*56.08/1e3:.3f} т CaO -> ${co2_lime[0]:.0f}-{co2_lime[1]:.0f}/т")
print(f"  против ${co2_pen[0]:.0f}-{co2_pen[1]:.0f}/т на едком натре\n")
lo1=lo0-naoh_cost[0]-co2_pen[0]+lime_cost[0]+co2_lime[0]
hi1=hi0-naoh_cost[1]-co2_pen[1]+lime_cost[1]+co2_lime[1]
print(f"{'вариант':<46}{'себестоимость':>20}")
print(f"{'как сейчас (мочевина + покупная щёлочь)':<46}{lo0:>9.0f}-{hi0:<10.0f}")
print(f"{'известь вместо щёлочи (маршрут В)':<46}{lo1:>9.0f}-{hi1:<10.0f}")
print(f"{'плюс свой аммиак (маршрут В + Б)':<46}{lo1-urea_cost[0]+mm[0]*GAS[0]/T:>9.0f}-{hi1-urea_cost[1]+mm[1]*GAS[1]/T:<10.0f}")
CAPEX=10.22e6
print(f"\nОкупаемость при капитале ${CAPEX/1e6:.2f} млн (+$0.3 млн на известковое хозяйство):")
cap2=CAPEX+0.3e6
print(f"{'цена':<26}{'сейчас':>22}{'с известью':>22}")
for nm,p in (("паритет $2 207",2207),("brownfield $2 596",2596),("greenfield $2 757",2757)):
    a=(p-lo0)*T; b=(p-lo1)*T
    print(f"{nm:<26}{(CAPEX/a if a>0 else 0):>21.1f}г{(cap2/b if b>0 else 0):>21.1f}г")
print(f"""
Известковый маршрут превращает проект из «окупается только в узком сегменте
при дешёвом газе» в «окупается на паритете с импортом». Это самый крупный
рычаг из всего, что найдено за сессию, и он же самый дешёвый в проверке.

Соль и хлор-щёлочь — красивая идея, но в Гане она разбивается о цену
электроэнергии, а не о доступность соли. Свой аммиак — верное направление,
но на 4 тоннах в сутки капитал съедает выгоду.""")
