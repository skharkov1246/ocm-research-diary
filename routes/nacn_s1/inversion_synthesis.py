def pick(cls,label):
    lo=hi=0.; cap=0.
    print(f"\n  --- {label} ---")
    for gname,items in cls:
        items=sorted(items,key=lambda z:-(z[1]+z[2])/2)
        best=items[0]
        print(f"  {gname}")
        for n,a,b,c in items:
            m="<= берём" if n==best[0] else "  (конкурент, не складываем)"
            print(f"    {n[:70]:<72}{a:>5.0f}-{b:<5.0f} $/т {m}")
